import 'package:astro/catalog.dart';

Star _star(
  int hr,
  int ra,
  int dec,
  double vmag,
  double bv, {
  int? flamsteed,
  GreekLetter? bayer,
  String? constellation,
  String? name,
  String spectral = 'A0V',
}) => Star(
  hr: hr,
  raTenthsOfSecond: ra,
  decArcsec: dec,
  pmRaMas: 0,
  pmDecMas: 0,
  vmag: vmag,
  bv: bv,
  parallaxMas: null,
  designation: StarDesignation(
    flamsteed: flamsteed,
    bayer: bayer,
    constellation: constellation,
  ),
  spectralType: spectral,
  properName: name,
);

